using System.ComponentModel.DataAnnotations;
using Grsms.Domain.Common;

namespace Grsms.Domain.Onboarding;

// Phase 20: the electronic personnel file. Database records, not Windows folders: a file per employee, categories
// ("folders") and documents. Files are not copied: a document points at the Attachments row (or holds a frozen letter).

/// <summary>
/// One category ("folder") of every personnel file. The seven built-in ones are seeded with fixed ids
/// (see <see cref="PersonnelFileCategories"/>); the list is a table so more can be added later without code changes.
/// </summary>
public class PersonnelFileCategory
{
    public int Id { get; set; }
    public string Name { get; set; } = string.Empty;
    public int SortOrder { get; set; }
}

/// <summary>The seeded categories (ids are fixed in the database).</summary>
public static class PersonnelFileCategories
{
    public const int RecruitmentDocuments = 1;
    public const int EmployeeRecords = 2;
    public const int IdentificationRecords = 3;
    public const int ComplianceRecords = 4;
    public const int OnboardingRecords = 5;
    public const int ProbationRecords = 6;
    public const int GeneratedLetters = 7;

    public static readonly IReadOnlyList<PersonnelFileCategory> All =
    [
        new() { Id = RecruitmentDocuments, Name = "Recruitment Documents", SortOrder = 1 },
        new() { Id = EmployeeRecords, Name = "Employee Records", SortOrder = 2 },
        new() { Id = IdentificationRecords, Name = "Identification Records", SortOrder = 3 },
        new() { Id = ComplianceRecords, Name = "Compliance Records", SortOrder = 4 },
        new() { Id = OnboardingRecords, Name = "Onboarding Records", SortOrder = 5 },
        new() { Id = ProbationRecords, Name = "Probation Records", SortOrder = 6 },
        new() { Id = GeneratedLetters, Name = "Generated Letters", SortOrder = 7 }
    ];
}

/// <summary>What a personnel file document is.</summary>
public enum PersonnelDocumentKind
{
    /// <summary>An uploaded file (an <c>Attachments</c> row: the stored path, original name, type, size, SHA-256).</summary>
    [Display(Name = "File")] File,

    /// <summary>A letter generated by GRSMS, frozen as HTML at the time it was filed (appointment, confirmation, ...).</summary>
    [Display(Name = "Letter")] Letter,

    /// <summary>A record kept elsewhere in GRSMS, e.g. a signed Personal Record Declaration (shown from its own table).</summary>
    [Display(Name = "Record")] Record
}

/// <summary>
/// An employee's electronic personnel file: opened automatically when the onboarding is completed (the employee activated),
/// then added to by later steps (probation, confirmation) and by HR.
/// </summary>
public class PersonnelFile : BaseEntity
{
    /// <summary>Reference, e.g. "PF-2026-0001". Unique.</summary>
    public string FileNumber { get; set; } = string.Empty;

    /// <summary>The employee (Users.Id). One file per employee (unique).</summary>
    public string EmployeeUserId { get; set; } = string.Empty;
    public string EmployeeName { get; set; } = string.Empty;
    public string? StaffNumber { get; set; }
    public string JobTitle { get; set; } = string.Empty;
    public int DepartmentId { get; set; }

    /// <summary>The onboarding the file was opened from.</summary>
    public int OnboardingRecordId { get; set; }

    public DateTime OpenedAt { get; set; }
}

/// <summary>One document in a personnel file.</summary>
public class PersonnelFileDocument : BaseEntity
{
    public int PersonnelFileId { get; set; }
    public int CategoryId { get; set; }
    public string Title { get; set; } = string.Empty;
    public PersonnelDocumentKind Kind { get; set; }

    /// <summary>For <see cref="PersonnelDocumentKind.File"/>: the Attachments row (the stored path is there).</summary>
    public int? AttachmentId { get; set; }

    /// <summary>For <see cref="PersonnelDocumentKind.Letter"/>: the letter as filed (HTML built from encoded values only).</summary>
    public string? Content { get; set; }

    /// <summary>Where the document came from, e.g. ("EmployeeDocument", 12), ("EmployeeDeclaration", 3), ("OnboardingRecord", 5).</summary>
    public string? SourceType { get; set; }
    public int? SourceId { get; set; }

    /// <summary>The date of the document itself (e.g. when it was uploaded or signed).</summary>
    public DateTime DocumentDate { get; set; }

    /// <summary>Who filed it (Users.Id); null when GRSMS filed it automatically.</summary>
    public string? AddedByUserId { get; set; }
}
